#!/usr/bin/env python3
"""
crlb_muap_benchmark.py -- Same six-optimizer Monte Carlo benchmark as
crlb_optimizer_benchmark.py, but with the source signal replaced: instead of
Shwedyk-PSD-colored noise (a signal that satisfies the constant-delay model
exactly by construction), each channel column here is a REAL biophysical
motor-unit action potential (MUAP) waveform generated by the Farina &
Merletti (2001) model (scripts/run_muap_grid.m), propagating with a known
CV, to which independent white noise is added for each SNR level.

This is a robustness check, not a replacement: the MUAP signal only
APPROXIMATELY satisfies the pure constant-delay model that both the MLE
estimator and the analytic CRLB assume (see crlb_optimizer_benchmark.py's
crlb_theta docstring) -- real propagation mildly reshapes the waveform
channel to channel (volume-conductor filtering, spatial attenuation), unlike
the Shwedyk case where every channel is an exact delayed copy. The fiber
geometry (scripts/run_muap_grid.m) was deliberately set up so the 13-channel
array sits well inside the fibre's mid-propagating region (away from both
the innervation zone and the tendon), which keeps this approximation good:
the multichannel MLE recovers the known CV to within ~1% on the clean
(noiseless) MUAP signal (see run log), confirming the model-mismatch bias is
small relative to the noise-driven variance studied here.

Requires scripts/muap_cv{3,4,4p5,5,6}.mat, produced by run_muap_grid.m.

Outputs:
  - journal_edit/optim_benchmark_muap_data.csv
  - journal_edit/crlb_vs_snr_muap.pdf   (MUAP-based figure, same layout as
                                         crlb_vs_snr.pdf, for side-by-side
                                         comparison)
"""
import sys
import time
from pathlib import Path

import numpy as np
import scipy.io as sio

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO))

from scripts.optimizer_crlb_paper.crlb_optimizer_benchmark import (  # noqa: E402
    CFG, GATE, SNR_VALUES, REPS_FAST, REPS_SLOW,
    coarse_grid, refine_golden, refine_brent, refine_newton,
    refine_sa, refine_ga, refine_pso, theta_to_cv,
)

CV_TAGS = {3.0: "3", 4.0: "4", 4.5: "4p5", 5.0: "5", 6.0: "6"}


def load_clean_muap(cv_true):
    p = REPO / "scripts" / "optimizer_crlb_paper" / f"muap_cv{CV_TAGS[cv_true]}.mat"
    d = sio.loadmat(p, squeeze_me=True, struct_as_record=False)
    return d["MUAP"].astype(float)


def add_noise(clean, snr_db, rng):
    p_sig = np.mean(clean ** 2)
    p_noise = p_sig / (10 ** (snr_db / 10))
    return clean + rng.standard_normal(clean.shape) * np.sqrt(p_noise)


def run_cell(clean, cv_true, snr_db, seed0):
    fast = {"grid+golden": [], "Brent": [], "Newton": []}
    fast_t = {"grid+golden": [], "Brent": [], "Newton": []}
    for r in range(REPS_FAST):
        rng = np.random.default_rng(seed0 + r)
        x = add_noise(clean, snr_db, rng)
        X, freqs, t0, step = coarse_grid(x)
        for name, fn in (("grid+golden", refine_golden), ("Brent", refine_brent),
                          ("Newton", refine_newton)):
            t1 = time.perf_counter()
            th = fn(X, freqs, t0, step)
            dt = (time.perf_counter() - t1) * 1e3
            fast[name].append(theta_to_cv(th))
            fast_t[name].append(dt)

    slow = {"SA": [], "GA": [], "PSO": []}
    slow_t = {"SA": [], "GA": [], "PSO": []}
    for r in range(REPS_SLOW):
        rng = np.random.default_rng(seed0 + 1000 + r)
        x = add_noise(clean, snr_db, rng)
        X, freqs, t0, step = coarse_grid(x)
        mc_rng = np.random.default_rng(seed0 + 2000 + r)
        for name, fn in (("SA", lambda *a: refine_sa(*a, mc_rng)),
                          ("GA", lambda *a: refine_ga(*a, mc_rng)),
                          ("PSO", lambda *a: refine_pso(*a, mc_rng))):
            t1 = time.perf_counter()
            th = fn(X, freqs, t0, step)
            dt = (time.perf_counter() - t1) * 1e3
            slow[name].append(theta_to_cv(th))
            slow_t[name].append(dt)

    all_times = {**fast_t, **slow_t}
    out = {}
    for name, ests in {**fast, **slow}.items():
        ests = np.asarray(ests)
        pct_err = 100.0 * (ests - cv_true) / cv_true
        timing = np.asarray(all_times[name])
        out[name] = dict(mean_abs_pct=np.mean(np.abs(pct_err)),
                          rmse_pct=np.sqrt(np.mean(pct_err ** 2)),
                          sd_pct=np.std(pct_err),
                          time_ms=np.mean(timing))
    return out


def main():
    method_names = ["grid+golden", "Brent", "Newton", "SA", "GA", "PSO"]
    cv_values = list(CV_TAGS.keys())
    rows = []
    agg = {m: {snr: [] for snr in SNR_VALUES} for m in method_names}

    for cv in cv_values:
        clean = load_clean_muap(cv)
        for snr in SNR_VALUES:
            seed0 = int(cv * 1000 + snr)
            res = run_cell(clean, cv, snr, seed0)
            for m in method_names:
                rows.append(dict(cv_true=cv, snr_db=snr, method=m, **res[m]))
                agg[m][snr].append(res[m]["rmse_pct"])
            print(f"cv={cv:>4} snr={snr:>4} done: "
                  + ", ".join(f"{m}={res[m]['rmse_pct']:.3f}%" for m in method_names))

    import csv
    csv_path = REPO / "journal_edit" / "optim_benchmark_muap_data.csv"
    with open(csv_path, "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=["cv_true", "snr_db", "method",
                                           "mean_abs_pct", "rmse_pct", "sd_pct", "time_ms"])
        w.writeheader()
        for r in rows:
            w.writerow(r)
    print(f"\nWrote {csv_path}")

    print("\n=== MUAP-based summary (RMSE %err range) ===")
    for m in method_names:
        lo_e = min(np.mean(agg[m][snr]) for snr in SNR_VALUES)
        hi_e = max(np.mean(agg[m][snr]) for snr in SNR_VALUES)
        print(f"{m:12s}: {lo_e:.3f}--{hi_e:.3f} %")

    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    COLORS = {"grid+golden": "#0B2A4A", "Brent": "#028090", "Newton": "#3C9D45",
              "SA": "#E08A1E", "GA": "#B23A48", "PSO": "#6A4C93"}
    fig, ax = plt.subplots(figsize=(6.0, 4.2))
    for m in method_names:
        ys = [np.mean(agg[m][snr]) for snr in SNR_VALUES]
        ax.plot(SNR_VALUES, ys, "o-", color=COLORS[m], label=m, lw=1.8, ms=5)
    ax.set_yscale("log")
    ax.set_xlabel("SNR [dB]")
    ax.set_ylabel("RMSE in CV [%]  (log scale)")
    ax.set_title("Optimizer comparison on real MUAP signal (Farina-Merletti)",
                  loc="left", fontsize=10)
    ax.grid(alpha=0.2, which="both")
    ax.legend(fontsize=8, framealpha=0.9)
    plt.tight_layout()
    fig_path = REPO / "journal_edit" / "crlb_vs_snr_muap.pdf"
    plt.savefig(fig_path)
    print(f"Wrote {fig_path}")


if __name__ == "__main__":
    main()
